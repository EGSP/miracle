import { Effect, FiberRef } from 'effect';

/**
 * Ambient-атрибуция расхода токенов LLM: набор строковых тегов (`orderId`, `userId`, `jobRunId`, …),
 * который «протекает» по дереву эффектов сверху вниз и читается на листе — в `YandexService` при
 * записи строки ledger.
 *
 * ## Зачем это и почему FiberRef
 *
 * Расход токенов фиксирует `YandexService` — синглтон без доступа к контексту вызова. А связать
 * запись нужно с заказом/пользователем/прогоном, которые известны НАВЕРХУ дерева джоб. Тащить их
 * параметром через каждый тул/джоб неудобно (тулы вообще не знают `jobRunId`). Поэтому используем
 * механизм самого Effect для «фоновых» контекстных данных — {@link FiberRef}: ровно так в Effect
 * реализованы `annotateLogs` и атрибуты спанов.
 *
 * ## Что такое FiberRef (коротко)
 *
 * FiberRef — это типизированный КЛЮЧ (а не хранилище): идентичность + значение по умолчанию +
 * политика наследования при форке. Само значение лежит в таблице КОНКРЕТНОЙ фибры. Свойства,
 * которые нам важны:
 * - **фиберо-локальность** — у параллельных веток значения независимы (не общий мутабельный стейт);
 * - **наследование вниз** — дочерняя фибра при форке получает КОПИЮ значения родителя
 *   (`Effect.all` с concurrency «просто работает»);
 * - **лексический скоуп** — `Effect.locallyWith` ставит значение лишь на время обёрнутого эффекта и
 *   его детей, а по выходе восстанавливает прежнее. Поэтому изменения ребёнка НЕ утекают ни в
 *   родителя, ни в соседнюю ветку.
 *
 * ## Кто и что пишет
 *
 * - `jobRunId` — рантайм джоб (`execute`) на каждом узле дерева;
 * - `orderId`/`userId`/`fileId` — корневой джоб/инициатор, которому они известны;
 * - явный override при необходимости — вызывающий через `request.tags` в `YandexService`.
 *
 * Бизнес-код НЕ обращается к FiberRef напрямую — только через {@link withTokensUsageScope}
 * (запись) и {@link currentTokensUsage} (чтение, внутреннее).
 */
export type TokensUsageTags = Record<string, string>;

/**
 * Приватный FiberRef-ключ ambient-тегов. Наружу не экспортируется намеренно: вся работа идёт через
 * {@link withTokensUsageScope}/{@link currentTokensUsage}, чтобы в коде не было прямых упоминаний
 * FiberRef и его семантики.
 *
 * `unsafeMake` — синхронное создание ключа на уровне модуля с дефолтом `{}`. «unsafe» лишь потому,
 * что это побочный эффект при загрузке модуля (а не управляемый через `Scope`); для постоянного
 * ambient-ключа это штатная идиома (так же создаются `current*`-рефы внутри Effect).
 */
const tagsRef = FiberRef.unsafeMake<TokensUsageTags>({});

/**
 * Привязывает теги атрибуции к расходу токенов на время `effect` и всех его дочерних эффектов.
 *
 * Сливает переданные `tags` поверх унаследованных (НЕ затирает их целиком), поэтому каждый уровень
 * дерева может добавлять своё: корень — `orderId`, узел — `jobRunId`. Скоуп лексический: по выходе
 * из `effect` значение возвращается к прежнему, ветки изолированы. Сигнатуру эффекта не меняет
 * (`R` не трогается) — промежуточные слои ничего не объявляют.
 *
 * @example
 * ```ts
 * // корневой джоб заказа
 * body.pipe(withTokensUsageScope({ orderId: input.orderId }));
 * // рантайм на каждом узле
 * job.run(input).pipe(withTokensUsageScope({ jobRunId: node.id }));
 * ```
 */
export const withTokensUsageScope =
    (tags: TokensUsageTags) =>
    <A, E, R>(effect: Effect.Effect<A, E, R>): Effect.Effect<A, E, R> =>
        Effect.locallyWith(effect, tagsRef, (current) => ({ ...current, ...tags }));

/**
 * Текущая накопленная атрибуция текущей фибры. Предназначена ТОЛЬКО для внутренних читателей
 * (`YandexService` при записи ledger); в бизнес-логике не использовать.
 */
export const currentTokensUsage: Effect.Effect<TokensUsageTags> = FiberRef.get(tagsRef);
