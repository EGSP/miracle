/**
 * Качественная уверенность LLM — единый enum для всех результатов анализа.
 *
 * Заменяет числовую шкалу `0..1`: число от модели — ложная точность (всё равно загонялось в
 * пороги и шумело). Перечисление честнее и убирает магические константы из кода подсветки.
 *
 * Маппинг на подсветку (см. `designation-display.ts`): `low` → критично, `medium` →
 * предупреждение, `high` → без подсветки.
 */
export type Confidence = 'high' | 'medium' | 'low';

/** Допустимые значения {@link Confidence} — для zod-схем (`z.enum(CONFIDENCE_VALUES)`) и валидации. */
export const CONFIDENCE_VALUES = ['high', 'medium', 'low'] as const;
